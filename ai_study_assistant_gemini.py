import time
from google.genai.errors import ServerError

def ai_study_assistant(question, task):

    prompt = f"""
    You are a helpful AI Study Assistant.

    Task: {task}
    Student Question: {question}

    Give a simple, clear and beginner-friendly answer.
    Include examples wherever useful.
    """

    for attempt in range(3):
        try:
            response = client.models.generate_content(
                model="gemini-3.8-flash",
                contents=prompt
            )
            return response.text

        except ServerError:
            if attempt < 2:
                print("Gemini is busy. Retrying...")
                time.sleep(5)
            else:
                return "Gemini is temporarily unavailable. Please try again later."

        except Exception as e:
            return f"An error occurred: {e}"

def ai_study_assistant(question, task):

    prompt = f"""
    You are a helpful AI Study Assistant.
    Task: {task}
    Student Question: {question}

    Give a simple, clear and beginner-friendly answer.
    Include examples wherever useful.
    """

    models = ["gemini-3.8-flash", "gemini-3.5-flash-lite"]

    for model in models:
        try:
            print("Using model:", model)

            response = client.models.generate_content(
                model=model,
                contents=prompt
            )

            return response.text

        except ServerError:
            print(f"{model} is temporarily busy.")
            continue

        except Exception as e:
            return f"Error: {e}"

    return "Both Gemini models are temporarily unavailable. Please try again later."

